! Gauss Legendre in 3D defined on the prism reference region

  subroutine Gauss_Legendre_numeric_prism ( p, n, x, w )

!   order of integration rule on the triangle base (=order polynomial
!   integrated exact).
    integer, intent(in) :: p

!   the number of integration points on the height
    integer, intent(in) :: n

!   the reference coordinates and weights of the integration points
!   x(ninti,ndim), w(ninti)
!   where ninti is number of integration points
    real(dp), intent(out), dimension(:,:) :: x
    real(dp), intent(out), dimension(:) :: w


    integer :: i, j, ip, m
    real(dp), allocatable :: x1(:,:), w1(:)
    real(dp), dimension(n) :: x2, w2

!   number of integration points on triangle
    integer, parameter, dimension(21) :: nt = &
    [  1,  3,  6,  6,  7, 12, 15, 16, 19, 25, &
      28, 33, 37, 46, 52, 55, 61, 72, 73, 88, &
      91 ]

!   test

    if ( p < 1 .or. p > size(nt) ) then
      write(*,'(/2a,i0/)') &
        'Error in Gauss_Legendre_numeric_triangle: ', &
        'invalid integration rule, p = ', p
      stop
    end if

    m = nt(p)

    if ( size(x,1) < m*n .or. size(w) < m*n ) then
      write(*,'(/a,i0/)') &
        'Error in Gauss_Legendre_numeric_triangle: size of x or w too small'
      stop
    end if

    allocate ( x1(m,2), w1(m) )

    call Gauss_Legendre_numeric_triangle ( p, x1, w1 )
    call Gauss_Legendre_numeric_line ( n, x2, w2 )

    do i = 1, m
      do j = 1, n
        ip = i + m * ( j - 1 )
        x(ip,1) = x1(i,1)
        x(ip,2) = x1(i,2)
        x(ip,3) = x2(j)
        w(ip)   = w1(i) * w2(j)
      end do
    end do

  end subroutine Gauss_Legendre_numeric_prism


! Set number of Gauss integration points for an element

  subroutine set_ninti_standard_numeric ( gauss, ninti )

    use limits_m, only: GAUSS_RULE

    type(gauss_t), intent(in) :: gauss

!   number of integration points
    integer, intent(out) :: ninti

!   number of integration points triangle
    integer, parameter, dimension(21) :: ntri = &
    [  1,  3,  6,  6,  7, 12, 15, 16, 19, 25, &
      28, 33, 37, 46, 52, 55, 61, 72, 73, 88, &
      91 ]

!   number of integration points tetrahedron
    integer, parameter, dimension(14) :: ntet = &
    [ 1, 4, 8, 14, 14, 24, 35, 46, 61, 81, 109, 140, 171, 236 ]

!   number of integration points hexahedron (ver2)
    integer, parameter, dimension(11) :: nhex2 = &
    [ 1, 6, 6, 14, 14, 34, 34, 58, 58, 90, 90 ]

!   number of integration points pyramid (ver2)
    integer, parameter, dimension(10) :: npyr2 = &
    [ 1, 5, 6, 10, 15, 24, 31, 47, 62, 83 ]

!   set integration

    if ( gauss%globalshape == 'line' ) then

      ninti = gauss%intrule

    else if ( gauss%globalshape == 'triangle' ) then

      if ( gauss%intrule >= 1 .and. gauss%intrule <= size(ntri) ) then

        ninti = ntri(gauss%intrule)

      else

        write(*,'(/a/a,i0/)') &
          'Error in set_ninti_standard_numeric: ', &
          '  invalid polynomial order for triangle, p = ', gauss%intrule
        stop

      end if

    else if ( gauss%globalshape == 'quadrilateral' ) then

        ninti = gauss%intrule ** 2

    else if ( gauss%globalshape == 'tetrahedron' ) then

      if ( gauss%intrule >= 1 .and. gauss%intrule <= size(ntet) ) then

        ninti = ntet(gauss%intrule)

      else

        write(*,'(/a/a,i0/)') &
          'Error in set_ninti_standard_numeric: ', &
          '  invalid polynomial order for tetrahedron, p = ', gauss%intrule
        stop

      end if

    else if ( gauss%globalshape == 'hexahedron' ) then

      if ( GAUSS_RULE == 2 ) then

        if ( gauss%intrule >= 1 .and. gauss%intrule <= size(nhex2) ) then

          ninti = nhex2(gauss%intrule)

        else

          write(*,'(/a/a,i0/)') &
            'Error in set_ninti_standard_numeric: ', &
            '  invalid polynomial order for hexahedron, p = ', gauss%intrule
          stop

        end if

      else

        ninti = gauss%intrule ** 3

      end if

    else if ( gauss%globalshape == 'prism' ) then

      if ( gauss%intrule >= 1 .and. gauss%intrule <= size(ntri) ) then

        ninti = ntri(gauss%intrule) * gauss%intrule2

      else

        write(*,'(/a/a,i0/)') &
          'Error in set_ninti_standard_numeric: ', &
          '  invalid polynomial order for triangle base, p = ', gauss%intrule
        stop

      end if

    else if ( gauss%globalshape == 'pyramid' ) then

      if ( gauss%intrule >= 1 .and. gauss%intrule <= size(npyr2) ) then

        ninti = npyr2(gauss%intrule)

      else

        write(*,'(/a/a,i0/)') &
          'Error in set_ninti_standard_numeric: ', &
          '  invalid polynomial order for pyramid, p = ', gauss%intrule
        stop

      end if

    else

      write(*,'(/2a/)') &
        'Error in set_ninti_standard_numeric: not available for ', &
        gauss%globalshape
      stop

    end if

  end subroutine set_ninti_standard_numeric

