      real(dp), intent(in) :: a

      real(dp), dimension(8*3) :: perm3

      perm3 = [  a, -a, -a, &
                -a,  a,  a, &
                -a,  a, -a, &
                -a, -a, -a, &
                -a, -a,  a, &
                 a,  a, -a, &
                 a,  a,  a, &
                 a, -a,  a ]

    end function perm3

    function perm4 ( a )

      real(dp), intent(in) :: a

      real(dp), dimension(12*3) :: perm4

      perm4 = [ -a, -a,  z, &
                 a,  z, -a, &
                 z,  a, -a, &
                 a,  a,  z, &
