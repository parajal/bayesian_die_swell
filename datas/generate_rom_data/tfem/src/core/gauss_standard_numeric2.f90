    function perm1 ( a )

      real(dp), intent(in) :: a

      real(dp), dimension(1*3) :: perm1

      perm1 = [ a, a, a ]

    end function perm1

    function perm2 ( a )

      real(dp), intent(in) :: a

      real(dp), dimension(6*3) :: perm2

      perm2 = [ -a,  z,  z, &
                 z,  z,  a, &
                 z,  a,  z, &
                 z,  z, -a, &
                 a,  z,  z, &
                 z, -a,  z ]

